# Pedir al usuario la medida del lado
lado = float(input("Ingresa la medida del lado del cuadrado: "))

# Calcular área y perímetro
area = lado * lado
perimetro = 4 * lado

# Mostrar resultados
print("\n--- RESULTADOS ---")
print(f"Área del cuadrado: {area}")
print(f"Perímetro del cuadrado: {perimetro}")
